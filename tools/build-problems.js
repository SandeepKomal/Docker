// Builds site/problems.html: every troubleshooting entry as plain HTML that
// reads without JavaScript, for search engines and for printing.
// Run with: node tools/build-problems.js   (tests/check_site_data.js checks it is current)
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const OUT = path.join(root, "site/problems.html");

// The site's scripts attach themselves to window; load them once, whoever asks first.
function load() {
  global.window = global.window || {};
  for (const [file, name] of [["site/data.js", "TRACK"], ["site/playground.js", "DQSim"]]) {
    const p = path.join(root, file);
    if (!window[name]) { delete require.cache[p]; require(p); }
  }
  return { Q: window.TRACK, titles: Object.fromEntries(window.DQSim.SCENARIOS.map((s) => [s.id, s.title])) };
}

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function build() {
  const { Q, titles } = load();
  const byId = Object.fromEntries(Q.doctor.map((d) => [d.id, d]));
  const section = (d) => {
    const lv = Q.levels.find((l) => l.id === d.level);
    return `    <section class="card fix problem" id="${d.id}">
      <h3>${esc(d.status)}</h3>
      <h4>The error</h4>
      <pre class="fix-error"><code>${esc(d.error)}</code></pre>
      <h4>Why it happens</h4>
      <p>${esc(d.meaning)}</p>
      <h4>Likely causes</h4>
      <ul>
${d.causes.map((c) => `        <li>${esc(c)}</li>`).join("\n")}
      </ul>
      <h4>Confirm</h4>
      <pre><code>${esc(d.commands.join("\n"))}</code></pre>
      <h4>Fix</h4>
      <ol>
${d.fix.map((f) => `        <li>${esc(f)}</li>`).join("\n")}
      </ol>
      <h4>Prevent it</h4>
      <p>${esc(d.prevent)}</p>
      <p class="note"><strong>Now learn it:</strong> break and fix it yourself in ${d.scenarios.map((id) => `<a href="index.html#play/${id}">${esc(titles[id])}</a>`).join(" · ")}, then take <a href="index.html#path">Level ${lv.id} · ${esc(lv.title)}</a>. <a href="index.html#fix/${d.id}">Open in DevOps Nimbus Docker</a>.</p>
    </section>`;
  };
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; connect-src 'none'; base-uri 'none'; form-action 'none'">
  <meta name="description" content="${esc(`Docker errors and how to fix them: ${Q.doctor.length} problems, each with the exact error message, what it means, how to confirm it, the fix and how to prevent it.`)}">
  <meta property="og:type" content="article">
  <meta property="og:title" content="Docker problems and fixes">
  <meta property="og:description" content="Exact Docker error messages with causes, confirming commands, fixes and prevention.">
  <meta property="og:url" content="${Q.site}problems.html">
  <link rel="canonical" href="${Q.site}problems.html">
  <title>Docker problems and fixes</title>
  <link rel="stylesheet" href="style.css">
  <link rel="icon" href="logo.svg" type="image/svg+xml">
</head>
<body>
  <!-- Generated by tools/build-problems.js from site/data.js. Do not edit by hand. -->
  <main class="wrap problems">
    <p class="eyebrow"><a href="index.html">DevOps Nimbus · Docker</a></p>
    <h1>Docker problems and fixes</h1>
    <p class="lede">${Q.doctor.length} problems people meet with Docker, each with the exact error, why it happens, how to confirm it, the fix and how to prevent it. Then learn it for good: break and fix each one yourself in the <a href="index.html#pg-title">browser playground</a>.</p>
    <nav class="card problems-index" aria-label="Problems">
${Q.doctorGroups.map(([group, ids]) => `      <h2>${esc(group)}</h2>
      <ul>
${ids.map((id) => `        <li><a href="#${id}">${esc(byId[id].status)}</a></li>`).join("\n")}
      </ul>`).join("\n")}
    </nav>
${Q.doctorGroups.map(([group, ids]) => `    <h2 class="section-title">${esc(group)}</h2>
${ids.map((id) => section(byId[id])).join("\n")}`).join("\n")}
  </main>
  <footer class="foot">
    <div class="wrap foot-base">
      <p>© 2024–2026 Sandeep Komal Pothu and contributors. Open source under the MIT License.</p>
      <p class="foot-tm">Docker® is a registered trademark of Docker, Inc. This project is independent and not affiliated with Docker, Inc.</p>
    </div>
  </footer>
</body>
</html>
`;
}

module.exports = { build, OUT };
if (require.main === module) {
  fs.writeFileSync(OUT, build());
  console.log(`wrote ${path.relative(root, OUT)}`);
}
